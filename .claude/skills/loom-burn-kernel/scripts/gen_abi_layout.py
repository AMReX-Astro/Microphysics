#!/usr/bin/env python3
"""Generate abi_layout.H: sizeof/offsetof static_asserts for every params
record that crosses the Loom kernel boundary (SKILL.md Phase 3, "Kernel ABI").

  gen_abi_layout.py --kernel-dir unit_test/test_react/loom/<port> [--cxx g++]

Finds every `struct <Name>Params { ... };` in the kernel directory's headers
(EosParams, RatesParams, NetParams, IntegratorParams, BurnParams, ...), lists
their data members, compiles a small host program that includes "burner.H"
and prints the measured sizes and offsets, and writes them as
`static_assert(...)` lines to <kernel-dir>/abi_layout.H. The shipped kernel
root (burn_kernel.cpp) includes abi_layout.H, so the same numbers are
checked by the host build (validators, launcher), by hipcc, and by the Loom
import: a layout difference between any of them fails the build instead of
silently corrupting parameters.

Run it after rates.H, network.H and loom_params.H exist (NEW_NETWORK.md
step 5), and again whenever a params struct changes. Members must be plain
declarations, one per line: `Real x;`, `int n;`, `long n;`, `Real a[N];`, or
a nested params record (`EosParams eos;`); anything else is an error, so the
script never guesses a layout. Python 3 standard library only.

Derived from the generator the Codex end-to-end run wrote (2026-10-19).
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

STRUCT_RE = re.compile(r'\bstruct\s+(\w+Params)\s*\{(.*?)\n\s*\};', re.S)
MEMBER_RE = re.compile(r'(?:const\s+)?([A-Za-z_][\w:]*)\s+([A-Za-z_]\w*)\s*(\[[^\]]+\])?\s*(?:=\s*[^;]*|\{[^}]*\})?;')


def records(kdir):
    found = {}
    for fn in sorted(os.listdir(kdir)):
        if not fn.endswith('.H') or fn.startswith('validate_') or fn == 'abi_layout.H':
            continue
        with open(os.path.join(kdir, fn)) as f:
            text = re.sub(r'//[^\n]*', '', f.read())
        for m in STRUCT_RE.finditer(text):
            name, body = m.group(1), m.group(2)
            fields = []
            for line in body.splitlines():
                line = line.strip()
                if not line:
                    continue
                mm = MEMBER_RE.fullmatch(line)
                if not mm:
                    sys.exit(f'gen_abi_layout: {fn}: struct {name}: cannot parse member line: {line!r}')
                fields.append(mm.group(2))
            if name in found:
                sys.exit(f'gen_abi_layout: struct {name} defined twice ({found[name][0]}, {fn})')
            found[name] = (fn, fields)
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--kernel-dir', required=True, help='the port kernel directory (contains burner.H)')
    ap.add_argument('--cxx', default=os.environ.get('CXX', 'g++'), help='host C++ compiler (default $CXX, else g++)')
    ap.add_argument('--out', help='output header (default <kernel-dir>/abi_layout.H)')
    a = ap.parse_args()
    kdir = os.path.abspath(a.kernel_dir)
    if not os.path.isfile(os.path.join(kdir, 'burner.H')):
        sys.exit(f'gen_abi_layout: no burner.H in {kdir}')
    recs = records(kdir)
    if 'BurnParams' not in recs:
        sys.exit('gen_abi_layout: no struct BurnParams found')

    lines = ['#include <cstddef>', '#include <cstdio>', '#include "burner.H"', 'int main() {']
    for name, (fn, fields) in recs.items():
        lines.append(f'    std::printf("// {name} ({fn})\\n");')
        lines.append(f'    std::printf("static_assert(sizeof(mpl::{name}) == %zu);\\n", sizeof(mpl::{name}));')
        for fld in fields:
            lines.append(f'    std::printf("static_assert(__builtin_offsetof(mpl::{name}, {fld}) == %zu);\\n",'
                         f' __builtin_offsetof(mpl::{name}, {fld}));')
    lines.append('}')
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, 'abi_layout_probe.cpp')
        exe = os.path.join(tmp, 'abi_layout_probe')
        with open(src, 'w') as f:
            f.write('\n'.join(lines) + '\n')
        r = subprocess.run([a.cxx, '-std=c++20', '-ffp-contract=off', '-I' + kdir, src, '-o', exe],
                           capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'gen_abi_layout: host compile failed:\n{r.stderr[-3000:]}')
        out = subprocess.run([exe], capture_output=True, text=True, check=True).stdout
    dst = a.out or os.path.join(kdir, 'abi_layout.H')
    with open(dst, 'w') as f:
        f.write('// GENERATED by the loom-burn-kernel skill, scripts/gen_abi_layout.py: host-measured\n'
                '// (LP64) layout of every params record that crosses the kernel boundary.\n'
                '// Included by burn_kernel.cpp, so host, hipcc and Loom builds all check it.\n'
                '// Regenerate after changing any *Params struct.\n'
                '#ifndef MPL_ABI_LAYOUT_H\n#define MPL_ABI_LAYOUT_H\n\n#include "burner.H"\n\n'
                + out + '\n#endif\n')
    nf = sum(len(v[1]) for v in recs.values())
    print(f'gen_abi_layout: {len(recs)} records ({", ".join(recs)}), {nf} fields -> {dst}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
