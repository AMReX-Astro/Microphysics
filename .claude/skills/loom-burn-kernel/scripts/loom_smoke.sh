#!/bin/bash
# Loom import + compile smoke test of kernel sources on this machine (the GPU
# host).
#
#   loom_smoke.sh launch NAME KERNEL_DIR SOURCE ROOT [ROOT ...]
#       Copy KERNEL_DIR (a directory of headers; SOURCE is a .cpp inside it)
#       to the run directory and start, detached: loom-import-cxx of SOURCE with
#       the given C++ roots (e.g. mpl::smoke_burn), then loom-compile of each
#       root for $LOOM_TARGET. Returns at once.
#   loom_smoke.sh status NAME
#       Print the run's log (import result; per root: compile result, seconds,
#       VGPR/AGPR/scratch from the code object notes; first error lines).
#       Exit 6 if the finished run had an import/compile failure.
#   loom_smoke.sh wait NAME [TIMEOUT]
#       Block until the run finishes (or dies, or TIMEOUT seconds pass,
#       default 7200), checking every 15 s, then print its log like status. Exit 0 when it finished,
#       4 when the job died, 5 on timeout, 6 when it finished but an import or
#       compile failed (or the tools md5 didn't match). Use it to run compiles one at a
#       time instead of hand-written polling (pgrep -f matches itself).
#   loom_smoke.sh fetch NAME DEST
#       Copy back the logs and compile reports (<root>.report.json; no IR, no
#       code objects).
#
# Environment:
#   LOOM_WORK         base dir                                   (default $HOME/loom-work)
#   LOOM_SMOKE_ROOT   run dirs, NAME/ inside                     (default $LOOM_WORK/loom-smoke)
#   LOOM_TOOLS        dir with loom-import-cxx, loom-compile and optionally
#                     tools.md5, built from the pinned commit    (required)
#   LOOM_TARGET       amdgpu target         (default: the GPU from amdgpu-arch/rocminfo, else gfx90a)
#   LOOM_CPUS         taskset CPU list away from timing cores    (default: all CPUs)
#   ROCM_PATH         ROCm install                               (default /opt/rocm)
#   LOOM_LLVM         llvm-readelf dir                           (default $ROCM_PATH/llvm/bin, else
#                                                                 $ROCM_PATH/lib/llvm/bin)
#   LOOM_IMPORT_TIMEOUT, LOOM_COMPILE_TIMEOUT  seconds           (default 1800, 3600)
#
# Never run full-kernel Loom compiles on a laptop (a Mac panicked); a GPU
# host with enough memory (8+ GB per compile) is fine.
set -u

rroot=${LOOM_SMOKE_ROOT:-${LOOM_WORK:-$HOME/loom-work}/loom-smoke}
run=(bash -c)

usage() { sed -n '2,/^set -u/p' "$0" | sed '$d'; exit "${1:-2}"; }

case "${1:-}" in
launch)
    [ $# -ge 5 ] || usage
    name=$2; kdir=$(cd "$3" && pwd) || exit 1; src=$4; shift 4
    : "${LOOM_TOOLS:?set LOOM_TOOLS to the dir with the frozen loom tools}"
    case "$name" in *[!A-Za-z0-9._-]*|'') echo "bad NAME"; exit 2;; esac
    [ -f "$kdir/$src" ] || [ -f "$src" ] || { echo "SOURCE must be a file inside KERNEL_DIR"; exit 2; }
    case "$src" in /*) src=${src#"$kdir"/};; esac
    stage=$(mktemp -d)
    mkdir -p "$stage/$name/k"
    (cd "$kdir" && COPYFILE_DISABLE=1 tar --no-xattrs -cf - .) | (cd "$stage/$name/k" && tar -xf -)
    roots_cxx="$*"
    cat > "$stage/$name/run.sh" <<EOF
#!/bin/bash
# generated by loom_smoke.sh launch
set -u
T='$LOOM_TOOLS'
export TMPDIR='$rroot/tmp'
mkdir -p "\$TMPDIR"
cd '$rroot/$name' || exit 1
echo \$\$ > RUNNING   # job PID: status/launch detect a job killed without cleanup (e.g. host reboot)
trap 'rm -f RUNNING' EXIT
rm -f RESULT; fail=0   # RESULT: ok | fail, read by wait/status (a missing file = job died)
R=\${ROCM_PATH:-/opt/rocm}
L='${LOOM_LLVM:-}'; [ -n "\$L" ] || { L=\$R/llvm/bin; [ -x "\$L/llvm-readelf" ] || L=\$R/lib/llvm/bin; }
TARGET='${LOOM_TARGET:-}'
[ -n "\$TARGET" ] || TARGET=\$({ "\$R/llvm/bin/amdgpu-arch" || "\$R/bin/rocminfo"; } 2>/dev/null | grep -m1 -o 'gfx[0-9a-f]*')
[ -n "\$TARGET" ] || { echo "# WARNING: no LOOM_TARGET and no GPU detected; falling back to gfx90a"; TARGET=gfx90a; }
CPUS='${LOOM_CPUS:-}'; CPUS=\${CPUS:-0-\$(( \$(nproc) - 1 ))}
echo "# \$(date) host=\$(hostname) target=\$TARGET cpus=\$CPUS source=$src"
if [ -f "\$T/tools.md5" ]; then (cd "\$T" && md5sum -c --quiet tools.md5) || { echo "TOOLS MD5 MISMATCH"; echo fail > RESULT; exit 1; }; fi
echo "# tools: \$(md5sum "\$T/loom-import-cxx" "\$T/loom-compile" | awk '{print \$1}' | tr '\n' ' ')"
roots=""
for r in $roots_cxx; do roots="\$roots --root=\$r"; done
t0=\$(date +%s)
if ! taskset -c "\$CPUS" timeout ${LOOM_IMPORT_TIMEOUT:-1800} "\$T/loom-import-cxx" --data-model=lp64 --fp-model=precise \$roots --output=kernel.loom "k/$src" > import.log 2>&1; then
  echo "IMPORT FAIL (\$(( \$(date +%s) - t0 ))s)"; grep -m8 -E "error" import.log | cut -c1-300; echo fail > RESULT; exit 0
fi
echo "import ok (\$(( \$(date +%s) - t0 ))s), \$(wc -l < kernel.loom) lines"
for r in $roots_cxx; do
  lr=\${r//::/.}; f=\${lr//./_}
  t0=\$(date +%s)
  if taskset -c "\$CPUS" timeout ${LOOM_COMPILE_TIMEOUT:-3600} "\$T/loom-compile" kernel.loom --root=\$lr \\
       --config=\$lr.workgroup_count.x=1 --config=\$lr.workgroup_count.y=1 --config=\$lr.workgroup_count.z=1 \\
       --format=amdgpu-hsaco --target=amdgpu:\$TARGET --compile-report=summary \\
       --compile-report-output=\$f.report.json --output=\$f.hsaco > \$f.compile.log 2>&1; then
    n=\$("\$L"/llvm-readelf --notes \$f.hsaco | awk '{for (j = 1; j < NF; j++) { if (\$j == ".vgpr_count:") v = \$(j+1); if (\$j == ".agpr_count:") a = \$(j+1); if (\$j == ".private_segment_fixed_size:") s = \$(j+1) }} END{printf "vgpr=%s agpr=%s scratch=%sB", v, a, s}')
    echo "\$r compile ok (\$(( \$(date +%s) - t0 ))s) \$n"
  else
    echo "\$r COMPILE FAIL (\$(( \$(date +%s) - t0 ))s)"; grep -m5 -E "error" \$f.compile.log | cut -c1-300
    fail=1
  fi
done
[ \$fail -eq 0 ] && echo ok > RESULT || echo fail > RESULT
echo "# done \$(date) result=\$(cat RESULT)"
EOF
    (cd "$stage" && COPYFILE_DISABLE=1 tar --no-xattrs -czf "$stage/payload.tgz" "$name")
    # Refuse if a run of this NAME is still going, unpack in the FOREGROUND (a
    # trailing & would background the whole && list and give tar /dev/null as
    # stdin), then background only the job on its own line.
    "${run[@]}" "R='$rroot'; W=\"\$R/$name\"
mkdir -p \"\$R\" || exit 1
if [ -e \"\$W/RUNNING\" ]; then
  if [ ! -s \"\$W/RUNNING\" ] || kill -0 \"\$(cat \"\$W/RUNNING\")\" 2>/dev/null; then echo \"BUSY: \$W has a running job (or a marker without PID)\"; exit 3; fi
  echo \"note: replacing stale RUNNING marker (job died; host up since \$(uptime -s))\"; rm -f \"\$W/RUNNING\"
fi
rm -rf \"\$W/k\" \"\$W\"/*.hsaco \"\$W/kernel.loom\" \"\$W/RESULT\"
tar xzf - -C \"\$R\" || { echo TAR-FAILED; exit 7; }
cd \"\$W\" || exit 8
nohup setsid bash run.sh > run.log 2>&1 < /dev/null &
sleep 1; echo \"launched $name at \$(date)\"" < "$stage/payload.tgz"
    rc=$?
    rm -rf "$stage"
    exit $rc
    ;;
status)
    [ $# -eq 2 ] || usage
    "${run[@]}" "cd '$rroot/$2' 2>/dev/null || { echo 'no such run'; exit 1; }
if [ -e RUNNING ]; then
  if [ ! -s RUNNING ]; then echo '(marker has no PID: launched by an older loom_smoke.sh; check ps for loom-compile)'
  elif kill -0 \$(cat RUNNING) 2>/dev/null; then echo '(still running)'
  else echo \"(JOB DIED without finishing: host up since \$(uptime -s); relaunch with the same NAME)\"; fi
fi
cat run.log
[ \"\$(cat RESULT 2>/dev/null)\" = fail ] && exit 6; exit 0"
    ;;
wait)
    [ $# -ge 2 ] && [ $# -le 3 ] || usage
    "${run[@]}" "cd '$rroot/$2' 2>/dev/null || { echo 'no such run'; exit 1; }
t0=\$(date +%s); rc=0
while [ -e RUNNING ]; do
  if [ ! -s RUNNING ] || ! kill -0 \$(cat RUNNING) 2>/dev/null; then
    echo \"(JOB DIED without finishing: host up since \$(uptime -s); relaunch with the same NAME)\"; rc=4; break
  fi
  if [ \$(( \$(date +%s) - t0 )) -ge ${3:-7200} ]; then echo '(still running: wait timed out)'; rc=5; break; fi
  sleep 15
done
cat run.log
if [ \$rc -eq 0 ] && [ \"\$(cat RESULT 2>/dev/null)\" != ok ]; then echo '(finished with an IMPORT/COMPILE FAIL or tools md5 mismatch)'; rc=6; fi
exit \$rc"
    ;;
fetch)
    [ $# -eq 3 ] || usage
    mkdir -p "$3"
    "${run[@]}" "cd '$rroot/$2' && tar czf - run.log run.sh import.log *.compile.log *.report.json 2>/dev/null" | tar xzf - -C "$3"
    ls "$3"
    ;;
-h|--help)
    usage 0
    ;;
*)
    usage
    ;;
esac
