#!/bin/bash
# Detached HIP build of test_react with the Loom launcher, in place.
#
#   build_test_react.sh KERNEL_SUBDIR
#       Start, detached, in unit_test/test_react of this checkout:
#         make -j$JOBS USE_HIP=TRUE AMD_ARCH=$ARCH NETWORK_DIR=... EOS_DIR=...
#           INTEGRATOR_DIR=... USE_NEUTRINOS=FALSE XTRA_CXXFLAGS=-ffp-contract=off
#           USE_LOOM_BURN=TRUE LOOM_KERNEL_DIR=KERNEL_SUBDIR $EXTRA_MAKE
#       KERNEL_SUBDIR is relative to test_react (e.g. loom/<port>). Returns at
#       once; the log is $LOOM_WORK/test_react-build/<stamp>/build.log.
#   build_test_react.sh status
#       Whether the last build is still running, and its log tail.
#   build_test_react.sh -h
#
# Environment:
#   NETWORK_DIR, EOS_DIR, INTEGRATOR_DIR   make variables         (required, no defaults)
#   ARCH        AMD_ARCH                  (default: the GPU from amdgpu-arch/rocminfo, else gfx90a)
#   JOBS        make -j                                          (default nproc)
#   ROCM_PATH   ROCm install                                     (default /opt/rocm)
#   AMREX_HOME  AMReX checkout                                   (required)
#   LOOM_WORK   base dir for build logs and TMPDIR               (default $HOME/loom-work)
#   EXTRA_MAKE  extra make arguments, word-split                 (default none)
#   HIPCC_COMPILE_FLAGS_APPEND, HIPCC_LINK_FLAGS_APPEND are passed through and logged.
set -u
usage() { sed -n '2,/^set -u/p' "$0" | sed '$d'; exit "${1:-2}"; }

B=${LOOM_WORK:-$HOME/loom-work}
ROOT=$B/test_react-build
LAST=$ROOT/last

case "${1:-}" in
-h|--help) usage 0;;
''|-*) usage;;
status)
    [ -d "$LAST" ] || { echo "no build started yet ($LAST missing)"; exit 1; }
    echo "build dir: $(cd "$LAST" && pwd -P)"
    if [ -e "$LAST/BUILDING" ]; then
        if kill -0 "$(cat "$LAST/BUILDING")" 2>/dev/null; then echo '(build still running)'
        else echo "(BUILD DIED without finishing; host up since $(uptime -s 2>/dev/null || uptime))"; fi
    fi
    tail -n 25 "$LAST/build.log" 2>/dev/null
    exit 0
    ;;
esac
[ $# -eq 1 ] || usage
ksub=${1%/}

top=$(git rev-parse --show-toplevel 2>/dev/null) || { echo "run inside the Microphysics checkout"; exit 2; }
tdir=$top/unit_test/test_react
case "$ksub" in /*|*..*) echo "KERNEL_SUBDIR must be relative to test_react, without .."; exit 2;; esac
[ -d "$tdir/$ksub" ] || { echo "KERNEL_SUBDIR $ksub is not a directory in $tdir"; exit 2; }
for v in NETWORK_DIR EOS_DIR INTEGRATOR_DIR AMREX_HOME; do
    [ -n "${!v:-}" ] || { echo "set $v (no default)"; exit 2; }
done
if [ -e "$LAST/BUILDING" ] && kill -0 "$(cat "$LAST/BUILDING")" 2>/dev/null; then
    echo "BUSY: a build is running ($(cd "$LAST" && pwd -P))"; exit 3
fi

R=${ROCM_PATH:-/opt/rocm}
ARCH=${ARCH:-}
if [ -z "$ARCH" ]; then
    ARCH=$({ "$R/llvm/bin/amdgpu-arch" || "$R/bin/rocminfo"; } 2>/dev/null | grep -m1 -o 'gfx[0-9a-f]*')
fi
[ -n "$ARCH" ] || { echo "WARNING: no ARCH given and no GPU detected; building for gfx90a" >&2; ARCH=gfx90a; }
S=$ROOT/$(date +%Y%m%d-%H%M%S)-$$
mkdir -p "$S" "$B/tmp" || exit 1
q() { printf '%q' "$1"; }
cat > "$S/build.sh" <<EOF
#!/bin/bash
# generated by build_test_react.sh
set -u
S=$(q "$S")
echo \$\$ > "\$S/BUILDING"
trap 'rm -f "\$S/BUILDING"' EXIT
export ROCM_PATH=$(q "$R")
export PATH="\$ROCM_PATH/bin:\$ROCM_PATH/llvm/bin:\$PATH"
export AMREX_HOME=$(q "$AMREX_HOME") MICROPHYSICS_HOME=$(q "$top") TMPDIR=$(q "${TMPDIR:-$B/tmp}")
$( [ -n "${HIPCC_COMPILE_FLAGS_APPEND:-}" ] && echo "export HIPCC_COMPILE_FLAGS_APPEND=$(q "$HIPCC_COMPILE_FLAGS_APPEND")" )
$( [ -n "${HIPCC_LINK_FLAGS_APPEND:-}" ] && echo "export HIPCC_LINK_FLAGS_APPEND=$(q "$HIPCC_LINK_FLAGS_APPEND")" )
cd $(q "$tdir") || exit 1
echo "# \$(date) host=\$(hostname) dir=\$PWD arch=$ARCH kernel=$ksub"
echo "# hipcc: \$(hipcc --version 2>/dev/null | grep -m1 -i 'HIP version')"
echo "# HIPCC_COMPILE_FLAGS_APPEND=\${HIPCC_COMPILE_FLAGS_APPEND:-} HIPCC_LINK_FLAGS_APPEND=\${HIPCC_LINK_FLAGS_APPEND:-}"
t0=\$(date +%s)
nice -n 10 make -j${JOBS:-\$(nproc)} USE_HIP=TRUE AMD_ARCH=$(q "$ARCH") NETWORK_DIR=$(q "$NETWORK_DIR") \\
    EOS_DIR=$(q "$EOS_DIR") INTEGRATOR_DIR=$(q "$INTEGRATOR_DIR") USE_NEUTRINOS=FALSE \\
    XTRA_CXXFLAGS=-ffp-contract=off USE_LOOM_BURN=TRUE LOOM_KERNEL_DIR=$(q "$ksub") ${EXTRA_MAKE:-}
rc=\$?
if [ \$rc -eq 0 ]; then
  echo "# BUILD OK (\$(( \$(date +%s) - t0 ))s): \$(ls -t ./*.ex 2>/dev/null | head -1)"
else
  echo "# BUILD FAILED rc=\$rc (\$(( \$(date +%s) - t0 ))s)"; grep -m10 -E 'error' "\$S/build.log" | cut -c1-300
fi
EOF
ln -sfn "$S" "$LAST"
cd "$S" || exit 1
nohup setsid bash build.sh > build.log 2>&1 < /dev/null &
sleep 1
echo "build started at $(date); log: $S/build.log (build_test_react.sh status)"
